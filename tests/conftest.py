"""Make sure the vendored tool_agent's SQLite fixture exists before any test needs it.

`query_database` reads `vendor/data/company.db`, generated by `vendor/generate_data.py`.
It's deterministic (no randomness), so regenerating it here is always safe and keeps
a fresh clone/CI runner green without a manual setup step.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

VENDOR_DIR = Path(__file__).resolve().parent.parent / "vendor"
DB_PATH = VENDOR_DIR / "data" / "company.db"

if not DB_PATH.exists():
    subprocess.run([sys.executable, "generate_data.py"], cwd=str(VENDOR_DIR), check=True)
